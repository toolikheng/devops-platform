#!/usr/bin/env bash
# aws-inventory.sh - write the Ansible inventory for the node in the ephemeral stack.
#
# Usage: aws-inventory.sh <inventory-file>   (make cloud-config passes ansible/inventory/aws.yml)
# The node gets a new instance ID every session, so the file is generated each time and gitignored. The
# host name is the instance ID itself: group_vars/aws.yml makes SSH pass it to Session Manager as the
# target, so no IP address or open port is involved.
set -euo pipefail

inventory="${1:?usage: aws-inventory.sh <inventory-file>}"
id="$(bash "$(dirname "$0")/node-id.sh")"

mkdir -p "$(dirname "$inventory")"
cat > "$inventory" <<EOF
# Generated by scripts/aws-inventory.sh from Terraform output. Rewritten every session; never committed.
aws:
  hosts:
    $id:
EOF
echo "aws-inventory: $inventory -> $id"
